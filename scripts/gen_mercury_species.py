#!/usr/bin/env python3
"""Generate the species data Pokémon Mercury v1.33 changes from its own ROM.

    python scripts/gen_mercury_species.py /path/to/mercury.gba

Mercury is a 32 MB FireRed rev 0 hack. Its gBaseStats is at 0x0976DFBC (found by
the game code's literal pools; the vanilla copy at 0x08254784 is unreferenced).
Species 1..386 are national 1..386; 53 new species (387..439) sit before Gen 4,
and from 440 on the national number is the internal id - 53 (Starly is 449 -> 396).
The maps below are only the ones the companion needs: types for every Mercury id,
and the national number for the shifted block. Names are looked up at runtime from
the app's Platinum/Black tables, then translated by the bundled Chinese names.

Writes app/src/main/kotlin/com/pokedaisy/app/companion/data/MercurySpeciesGen.kt.
"""
import hashlib
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/MercurySpeciesGen.kt")
SHA1 = "2d0d2b269199b90564e141518ad0e44cb2ada04f"
B = 0x08000000
BASE_STATS = 0x0976DFBC
SPECIES_TO_NATIONAL = 0x097E7A76
MAX_SPECIES = 650
GEN4_START = 440          # Turtwig, national 387
GEN4_SHIFT = 53
NATIONAL_COUNT = 1025


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    rom = open(sys.argv[1], "rb").read()
    got = hashlib.sha1(rom).hexdigest()
    if got != SHA1:
        raise SystemExit(f"not Mercury v1.33: sha1 {got}, expected {SHA1}")

    types, national, stats = {}, {}, {}
    for sp in range(1, MAX_SPECIES + 1):
        o = BASE_STATS - B + sp * 28
        rec = rom[o:o + 28]
        if len(rec) < 28:
            break
        hp, atk, df, spe, spa, spd, t1, t2 = rec[:8]
        if t1 >= 24 or t2 >= 24:
            continue
        # 0/0 stats with both types 0 is the table's empty tail; species 0 itself is skipped.
        if hp == atk == df == spe == spa == spd == 0 and t1 == t2 == 0:
            continue
        types[sp] = (t1, t2)
        stats[sp] = (hp, atk, df, spe, spa, spd)
        n = struct.unpack_from("<H", rom, SPECIES_TO_NATIONAL - B + sp * 2)[0]
        if 1 <= n <= NATIONAL_COUNT:
            national[sp] = n

    assert types[449] == (0, 2), types.get(449)          # Starly: Normal / Flying
    assert national[19] == 19 and national[20] == 20
    assert national[449] == 396
    assert stats[449] == (40, 55, 30, 60, 30, 30), stats.get(449)
    assert stats[546] == (120, 120, 120, 120, 120, 120)   # Arceus (493 + 53)

    lines = [
        "package com.pokedaisy.app.companion.data",
        "",
        "// GENERATED by scripts/gen_mercury_species.py from 宝可梦水银 v1.33 (sha1 2d0d2b26...).",
        "// Its own gBaseStats at 0x0976DFBC and sSpeciesToNationalPokedexNum at 0x097E7A76.",
        "// The full table matters: internal 19 -> national 19, 20 -> 20, 158 -> 158, 449 -> 396.",
        "// (An identity map for ids <= 386 made Rattata read as Raticate.)",
        "// Names are resolved at runtime from the Platinum/Black tables + the bundled Chinese names.",
        "",
        f"val mercurySpeciesNational: Map<Int, Int> = mapOf(",
    ]
    lines += [f"    {i} to {n}," for i, n in sorted(national.items())]
    lines += [")", "", "val mercurySpeciesTypes: Map<Int, SpeciesTypes> = mapOf("]
    lines += [f"    {i} to SpeciesTypes({t1}, {t2})," for i, (t1, t2) in sorted(types.items())]
    lines += [")", "", "val mercuryBaseStats: Map<Int, IntArray> = mapOf("]
    lines += [f"    {i} to intArrayOf({', '.join(str(x) for x in v)})," for i, v in sorted(stats.items())]
    lines += [")", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(types)} species, {len(national)} national ids)")


if __name__ == "__main__":
    main()
