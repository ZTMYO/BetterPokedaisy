#!/usr/bin/env python3
"""Generate the Chinese Pokédex descriptions from the bundled pokedex.json.

    python scripts/gen_zh_dex_descriptions.py \
        --pokedex PATH/pokedex.json \
        --texts PATH/pokeemerald-zh-main/src/data/pokemon/pokedex_text.h \
        [--out PATH]

The English side comes from pokeemerald-zh-main's pokedex_text.h (the ROM's
own Emerald text, used to check the entry before showing Chinese); the Chinese
descriptions are the bundled MIT-licensed text. Each row is
"Chinese description\\u0001English text", by national dex number.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/kotlin/com/pokedaisy/app/companion/data/ChineseDexDescriptionsGen.kt"


def unescape(s: str) -> str:
    return (s.replace("\\p", "\n\n").replace("\\n", "\n").replace('\\"', '"')
            .replace("\\'", "'").replace("\\\\", "\\"))


def cstrings(body: str) -> str:
    return "".join(unescape(m.group(1)) for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', body))


def kt(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n").replace("\r", "")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pokedex", required=True, help="the pokedex.json with index/description fields")
    ap.add_argument("--texts", required=True, help="pokeemerald-zh-main's src/data/pokemon/pokedex_text.h")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    texts = [cstrings(m.group(2)) for m in re.finditer(
        r"const u8 g(\w+)PokedexText\[\]\s*=\s*_\((.*?)\);", Path(args.texts).read_text(encoding="utf-8"), re.S)]
    if len(texts) < 387:
        raise SystemExit(f"expected at least 387 dex texts, found {len(texts)}")

    entries = {}
    names = {}
    for e in json.loads(Path(args.pokedex).read_text(encoding="utf-8")):
        try:
            n = int(e.get("index", "0"))
        except (TypeError, ValueError):
            continue
        if 1 <= n <= 386 and n not in entries and e.get("description"):
            entries[n] = e["description"].strip()
            names[n] = e.get("name_en") or ""

    missing = [n for n in range(1, 387) if not entries.get(n)]
    if missing:
        raise SystemExit(f"the pokedex has no description for {missing}")

    out = [
        "package com.pokedaisy.app.companion.data",
        "",
        "// Generated by scripts/gen_zh_dex_descriptions.py.",
        "// Chinese: bundled Pokédex descriptions (MIT);",
        "// English: pokeemerald-zh-main's pokedex_text.h, the ROM's own text the entry is checked against.",
        "// Each row: Chinese description\\u0001English text, by national dex number.",
        "internal val chineseDexDescriptions: Array<String> = arrayOf(",
        '    "", // 0: none',
    ]
    for n in range(1, 387):
        en = texts[n]
        zh = kt(entries[n])
        out.append(f'    "{zh}\\u0001{kt(en)}", // {n}: {names.get(n, "")}')
    out.append(")")
    out.append("")
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {args.out} ({len(entries)} descriptions)")


if __name__ == "__main__":
    main()
