#!/usr/bin/env python3
"""Generate Mercury v1.33's move names from its own gMoveNames.

    python scripts/gen_mercury_moves.py /path/to/mercury.gba

Mercury's move ids follow the CFRU/expanded numbering (497 = 蹭蹭脸颊 / Nuzzle,
609 = 集沙 / Shore Up), so the app can take type and power from its existing
CFRU move table by the same id. Names are 13-byte records at 0x081D97385 (move 1
first), in ELITE_REDUX_CN's Chinese charmap.

Writes app/src/main/kotlin/com/pokedaisy/app/companion/data/MercuryMovesGen.kt.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/MercuryMovesGen.kt")
CJK = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/CjkTables.kt")
SHA1 = "2d0d2b269199b90564e141518ad0e44cb2ada04f"
B = 0x08000000
NAMES = 0x09D97385
STRIDE = 13
COUNT = 1000


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    rom = open(sys.argv[1], "rb").read()
    got = hashlib.sha1(rom).hexdigest()
    if got != SHA1:
        raise SystemExit(f"not Mercury v1.33: sha1 {got}, expected {SHA1}")

    src = open(CJK, encoding="utf-8").read()
    body = re.search(r"val ELITE_REDUX_CN = intArrayOf\((.*?)\n\s*\)", src, re.S).group(1)
    pairs = sorted(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", body))

    def char(code: int):
        lo, hi = 0, len(pairs) - 1
        while lo <= hi:
            mid = (lo + hi) // 2
            c = pairs[mid] >> 16
            if c < code:
                lo = mid + 1
            elif c > code:
                hi = mid - 1
            else:
                return chr(pairs[mid] & 0xFFFF)
        return None

    def decode(raw: bytes) -> str:
        out, i = [], 0
        while i < len(raw):
            c = raw[i]
            if c == 0xFF:
                break
            if c in (0xFC, 0xFD):
                i += 2
                continue
            if c in (0xFE, 0xFA, 0xFB):
                out.append(" ")
                i += 1
                continue
            if i + 1 < len(raw):
                ch = char((c << 8) | raw[i + 1])
                if ch is not None:
                    out.append(ch)
                    i += 2
                    continue
            ch = char(c)
            out.append(ch if ch is not None else "?")
            i += 1
        return "".join(out)

    names = {}
    for mid in range(1, COUNT):
        off = NAMES - B + (mid - 1) * STRIDE
        name = decode(rom[off:off + STRIDE]).strip()
        if name and "?" not in name:
            names[mid] = name

    assert names[1] == "拍击", names.get(1)
    assert names[98] == "电光一闪", names.get(98)
    assert names[497] == "蹭蹭脸颊", names.get(497)

    lines = [
        "package com.pokedaisy.app.companion.data",
        "",
        "// GENERATED by scripts/gen_mercury_moves.py from 宝可梦水银 v1.33 (sha1 2d0d2b26...).",
        "// gMoveNames at 0x09D97385, 13-byte records from move 1; Mercury uses the CFRU/expanded",
        "// move ids (497 = 蹭蹭脸颊), so type and power come from moveDataUnbound by the same id.",
        "",
        "val mercuryMoveNames: Map<Int, String> = mapOf(",
    ]
    lines += [f'    {i} to "{n.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}",' for i, n in sorted(names.items())]
    lines += [")", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(names)} moves)")


if __name__ == "__main__":
    main()
