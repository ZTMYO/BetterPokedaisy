#!/usr/bin/env python3
"""Generate the Chinese game-name tables from PKHeX's text resources.

PKHeX keeps one name per line, index = id (line 1 is id 0, a placeholder):

  third_party source files (PKHeX, GPL-3.0):
    PKHeX.Core/Resources/text/other/zh-Hans/text_Moves_zh-Hans.txt
    PKHeX.Core/Resources/text/other/en/text_Moves_en.txt
    PKHeX.Core/Resources/text/other/zh-Hans/text_Abilities_zh-Hans.txt
    PKHeX.Core/Resources/text/other/en/text_Abilities_en.txt
    PKHeX.Core/Resources/text/items/gen3/text_ItemsG3_zh-Hans.txt
    PKHeX.Core/Resources/text/items/gen3/text_ItemsG3_en.txt   (UTF-16LE)
    PKHeX.Core/Resources/text/other/zh-Hans/text_Natures_zh-Hans.txt
    PKHeX.Core/Resources/text/other/en/text_Natures_en.txt
    PKHeX.Core/Resources/text/locations/gen3/text_rsefrlg_00000_zh-Hans.txt
    PKHeX.Core/Resources/text/locations/gen3/text_rsefrlg_00000_en.txt

Run:
  python scripts/gen_zh_names.py \
    --moves-zh PATH/text_Moves_zh-Hans.txt --moves-en PATH/text_Moves_en.txt \
    --abilities-zh PATH/text_Abilities_zh-Hans.txt --abilities-en PATH/text_Abilities_en.txt \
    --items-zh PATH/text_ItemsG3_zh-Hans.txt --items-en PATH/text_ItemsG3_en.txt \
    --natures-zh PATH/text_Natures_zh-Hans.txt --natures-en PATH/text_Natures_en.txt \
    --locations-zh PATH/text_rsefrlg_00000_zh-Hans.txt --locations-en PATH/text_rsefrlg_00000_en.txt

Each generated row is "简体中文|English"; the English half verifies a ROM's own
name before the Chinese one is shown, so hacks that reuse an id keep their text.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "app/src/main/kotlin/com/pokedaisy/app/companion/data"


def read_lines(path, utf16=False):
    data = Path(path).read_bytes()
    text = data.decode("utf-16" if utf16 else "utf-8-sig")
    lines = [line.rstrip("\r") for line in text.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def kotlin_string(s):
    return json.dumps(s, ensure_ascii=False).replace("$", r"\$")


def pair(zh_lines, en_lines, label):
    if len(zh_lines) != len(en_lines):
        raise SystemExit(f"{label}: {len(zh_lines)} Chinese lines != {len(en_lines)} English lines")
    rows = []
    for i, (zh, en) in enumerate(zip(zh_lines, en_lines)):
        zh, en = zh.strip(), en.strip()
        if i == 0:
            rows.append("")
            continue
        if "|" in zh or "|" in en:
            raise SystemExit(f"{label} id {i}: a name contains '|'")
        rows.append(f"{zh}|{en}" if zh and en else "")
    return rows


def write_array(path, name, rows, header):
    lines = [
        "package com.pokedaisy.app.companion.data",
        "",
        *header,
        f"internal val {name}: Array<String> = arrayOf(",
    ]
    lines += [f"    {kotlin_string(row)}," for row in rows]
    lines += [")", ""]
    content = "\n".join(lines)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} entries to {path.relative_to(ROOT)}")


def natures(zh_path, en_path):
    zh, en = read_lines(zh_path), read_lines(en_path)
    if len(zh) != 25 or len(en) != 25:
        raise SystemExit(f"natures: expected 25 rows, got {len(zh)} Chinese and {len(en)} English")
    rows = [f"{z.strip()}|{e.strip()}" for z, e in zip(zh, en)]
    if any(not z or not e for z, e in (row.split("|", 1) for row in rows)):
        raise SystemExit("natures: an empty Chinese or English name")
    return rows


def plain_pairs(zh_path, en_path, label):
    zh, en = read_lines(zh_path), read_lines(en_path)
    if len(zh) != len(en):
        raise SystemExit(f"{label}: {len(zh)} Chinese lines != {len(en)} English lines")
    rows = []
    for z, e in zip(zh, en):
        z, e = z.strip(), e.strip()
        if not z or not e:
            continue
        if "|" in z or "|" in e:
            raise SystemExit(f"{label}: a name contains '|'")
        rows.append(f"{z}|{e}")
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ("moves-zh", "moves-en", "abilities-zh", "abilities-en", "items-zh", "items-en",
                 "natures-zh", "natures-en", "locations-zh", "locations-en"):
        parser.add_argument("--" + flag, required=True, type=Path)
    args = parser.parse_args()

    moves = pair(read_lines(args.moves_zh), read_lines(args.moves_en), "moves")
    abilities = pair(read_lines(args.abilities_zh), read_lines(args.abilities_en), "abilities")
    items = pair(read_lines(args.items_zh), read_lines(args.items_en, utf16=True), "items")
    natures_rows = natures(args.natures_zh, args.natures_en)
    locations = plain_pairs(args.locations_zh, args.locations_en, "locations")

    header = [
        "// Generated by scripts/gen_zh_names.py from PKHeX's zh-Hans and English text resources,",
        "// PKHeX (https://github.com/kwsch/PKHeX), GPL-3.0 (third_party/licenses/PKHeX-GPL-3.0.txt).",
        "// Each row: Simplified Chinese name|English name (the English name verifies the ROM's own).",
    ]
    write_array(DATA / "ChineseMoveNamesGen.kt", "chineseMoveNames", moves, header)
    write_array(DATA / "ChineseAbilityNamesGen.kt", "chineseAbilityNames", abilities, header)
    write_array(DATA / "ChineseItemNamesGen.kt", "chineseItemNames", items, header)
    write_array(DATA / "ChineseNatureNamesGen.kt", "chineseNatureNames", natures_rows, header)
    write_array(DATA / "ChineseLocationNamesGen.kt", "chineseLocationNames", locations, header)


if __name__ == "__main__":
    main()
