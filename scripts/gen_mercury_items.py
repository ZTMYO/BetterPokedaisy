#!/usr/bin/env python3
"""Generate Mercury v1.33's item names from its own gItems.

    python scripts/gen_mercury_items.py /path/to/mercury.gba

Mercury is a 32 MB FireRed rev 0 hack. Its gItems is at 0x087C7E00 (the
unreferenced vanilla copy at 0x083DB028 is not the game's); records are vanilla
struct Item (44 bytes, name[14], itemId +0x0E, description pointer +0x14) and
the names are in ELITE_REDUX_CN's Chinese charmap. Item 58 is 肌力之羽.

Writes app/src/main/kotlin/com/pokedaisy/app/companion/data/MercuryItemsGen.kt.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/MercuryItemsGen.kt")
CJK = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/CjkTables.kt")
SHA1 = "2d0d2b269199b90564e141518ad0e44cb2ada04f"
B = 0x08000000
ITEMS = 0x087C7E00
STRIDE = 44
COUNT = 2000


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    rom = open(sys.argv[1], "rb").read()
    got = hashlib.sha1(rom).hexdigest()
    if got != SHA1:
        raise SystemExit(f"not Mercury v1.33: sha1 {got}, expected {SHA1}")

    src = open(CJK, encoding="utf-8").read()
    body = re.search(r"val ELITE_REDUX_CN = intArrayOf\((.*?)\n\s*\)", src, re.S).group(1)
    pairs = sorted(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", body))

    def char(code: int):
        lo, hi = 0, len(pairs) - 1
        while lo <= hi:
            mid = (lo + hi) // 2
            c = pairs[mid] >> 16
            if c < code:
                lo = mid + 1
            elif c > code:
                hi = mid - 1
            else:
                return chr(pairs[mid] & 0xFFFF)
        return None

    def decode(raw: bytes) -> str:
        out, i = [], 0
        while i < len(raw):
            c = raw[i]
            if c == 0xFF:
                break
            if c in (0xFC, 0xFD):
                i += 2
                continue
            if c in (0xFE, 0xFA, 0xFB):
                out.append(" ")
                i += 1
                continue
            if i + 1 < len(raw):
                ch = char((c << 8) | raw[i + 1])
                if ch is not None:
                    out.append(ch)
                    i += 2
                    continue
            ch = char(c)
            out.append(ch if ch is not None else "?")
            i += 1
        return "".join(out)

    names = {}
    for slot in range(COUNT):
        off = ITEMS - B + slot * STRIDE
        rec = rom[off:off + STRIDE]
        if len(rec) < STRIDE:
            break
        name = decode(rec[:14]).strip()
        iid = int.from_bytes(rec[14:16], "little")
        if not name or not iid or iid >= COUNT or "?" in name:
            continue
        # A record whose id doesn't match its slot is another table's data.
        if iid != slot:
            continue
        names[iid] = name

    assert names[58] == "肌力之羽", names.get(58)
    assert names[13] == "伤药", names.get(13)
    assert names[57] == "体力之羽", names.get(57)

    lines = [
        "package com.pokedaisy.app.companion.data",
        "",
        "// GENERATED by scripts/gen_mercury_items.py from 宝可梦水银 v1.33 (sha1 2d0d2b26...).",
        "// Its own gItems at 0x087C7E00 (not the unreferenced vanilla copy at 0x083DB028),",
        "// decoded with ELITE_REDUX_CN. Keyed by the record's item id.",
        "",
        "val mercuryItemNames: Map<Int, String> = mapOf(",
    ]
    lines += [f'    {i} to "{n.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))}",' for i, n in sorted(names.items())]
    lines += [")", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(names)} items)")


if __name__ == "__main__":
    main()
